//! The cargo-driven island builder (PLAN §6 "Build driver").
//!
//! [`CargoIslandBuilder`] compiles [`IslandSource`]s to `.wasm` and generates their glue:
//!
//! 1. Each island's **cache key** hashes its sources, the embedded `trioxide_rt` sources and
//!    version, the generated manifests (which fix the profile), `rustc -vV`, and the
//!    `wasm-opt` version when it runs. A key already in `<cache_dir>/wasm/` is served without
//!    running cargo.
//! 2. Misses are **staged** into one cargo workspace, `<cache_dir>/build/`: the runtime in
//!    `trioxide_rt/`, each island in `islands/island_<key>/` with a manifest the builder
//!    writes (the island's own `Cargo.toml` is only for editing). The workspace pins the
//!    release profile: opt-level 3, fat LTO, one codegen unit, `panic = "abort"`.
//! 3. **One** `cargo build --release --target wasm32-unknown-unknown --keep-going` builds
//!    every miss in parallel, sharing the target directory, so `trioxide_rt` and `libm`
//!    compile once. A file lock serialises concurrent builds of the same cache.
//! 4. `wasm-opt -O3` runs when enabled and on `PATH`; then the module goes into the cache.

use std::{
    collections::{BTreeMap, BTreeSet},
    io::Write as _,
    path::{Path, PathBuf},
    sync::{
        OnceLock,
        atomic::{AtomicUsize, Ordering},
    },
};

use crate::{
    BuildError, IslandArtifact, IslandBuilder,
    glue::{GlueOptions, generate_glue},
    spec::{ABI_VERSION, IslandSpec, SpecError},
    toolchain::{self, Probe, Rustc, Tool, WASM_TARGET},
};

/// The `libm` requirement of `trioxide_rt`, repeated in the runtime manifest the builder
/// writes. A test checks it matches `crates/trioxide_rt/Cargo.toml`.
pub const RT_LIBM_REQUIREMENT: &str = "=0.2.16";

/// The runtime's sources, embedded so installed trioxide binaries can build islands without
/// a checkout. A test checks the list matches `crates/trioxide_rt/src`.
pub(crate) const RT_SOURCES: &[(&str, &str)] = &[
    ("src/abi.rs", include_str!("../../trioxide_rt/src/abi.rs")),
    (
        "src/array.rs",
        include_str!("../../trioxide_rt/src/array.rs"),
    ),
    ("src/conv.rs", include_str!("../../trioxide_rt/src/conv.rs")),
    ("src/fpu.rs", include_str!("../../trioxide_rt/src/fpu.rs")),
    ("src/lib.rs", include_str!("../../trioxide_rt/src/lib.rs")),
    ("src/math.rs", include_str!("../../trioxide_rt/src/math.rs")),
    ("src/ops.rs", include_str!("../../trioxide_rt/src/ops.rs")),
];

/// The version of the embedded runtime.
pub const RT_VERSION: &str = env!("CARGO_PKG_VERSION");

const WORKSPACE_MANIFEST: &str = r#"# Generated by trioxide: the staging workspace for WASM islands. Do not edit.
[workspace]
resolver = "3"
members = ["trioxide_rt", "islands/*"]

[profile.release]
opt-level = 3
lto = "fat"
codegen-units = 1
panic = "abort"
debug = false
strip = true
incremental = false
overflow-checks = false
debug-assertions = false
"#;

fn runtime_manifest() -> String {
    format!(
        r#"# Generated by trioxide. Do not edit.
[package]
name = "trioxide_rt"
version = "{RT_VERSION}"
edition = "2024"
publish = false

[features]
std = []

[dependencies]
libm = "{RT_LIBM_REQUIREMENT}"
"#
    )
}

fn island_manifest(package: &str, runtime: &str) -> String {
    format!(
        r#"# Generated by trioxide. Do not edit.
[package]
name = "{package}"
version = "0.0.0"
edition = "2024"
publish = false

[lib]
crate-type = ["cdylib"]
path = "src/lib.rs"

[dependencies]
trioxide_rt = {{ {runtime}, features = ["std"] }}
"#
    )
}

/// The Rust source of one island: its [`IslandSpec`] and the files of its crate.
///
/// This is what the Rust backend produces (and what `--debug-island` loads from disk). Only
/// the files under `src/` take part in the build; the builder writes the manifest itself.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct IslandSource {
    /// The boundary contract.
    pub spec: IslandSpec,
    /// Crate files by path relative to the crate root, `/`-separated. Must contain
    /// `src/lib.rs`; every path must be under `src/`.
    pub files: BTreeMap<String, String>,
}

impl IslandSource {
    /// An island from a spec and its `src/lib.rs`.
    pub fn new(spec: IslandSpec, lib_rs: String) -> Self {
        Self {
            spec,
            files: BTreeMap::from([("src/lib.rs".to_string(), lib_rs)]),
        }
    }

    /// Loads an island directory: `island.json` (the spec) plus every `.rs` file under
    /// `src/`.
    pub fn load(dir: &Path) -> Result<Self, BuildError> {
        let spec_path = dir.join("island.json");
        let json =
            std::fs::read_to_string(&spec_path).map_err(|e| BuildError::io(&spec_path, &e))?;
        let spec = IslandSpec::from_json(&json).map_err(|e| {
            BuildError::InvalidSpec(SpecError {
                island: dir.display().to_string(),
                message: format!("{}: {e}", spec_path.display()),
            })
        })?;
        let mut files = BTreeMap::new();
        collect_rust_files(dir, &dir.join("src"), &mut files)?;
        Ok(Self { spec, files })
    }

    /// Checks the spec and the file list.
    pub fn validate(&self) -> Result<(), SpecError> {
        self.spec.validate()?;
        let error = |message: String| SpecError {
            island: self.spec.id.0.clone(),
            message,
        };
        if !self.files.contains_key("src/lib.rs") {
            return Err(error("the crate has no src/lib.rs".into()));
        }
        for path in self.files.keys() {
            let safe = path.starts_with("src/")
                && path
                    .split('/')
                    .all(|part| !part.is_empty() && part != "." && part != "..");
            if !safe {
                return Err(error(format!("file `{path}` is not under src/")));
            }
        }
        Ok(())
    }

    /// A standalone `Cargo.toml` for the crate, depending on the runtime at `runtime_dir`.
    /// `--emit=rust` writes it so the emitted crate builds as is.
    pub fn manifest(&self, runtime_dir: &Path) -> String {
        let runtime = format!("path = {}", toml_string(&runtime_dir.display().to_string()));
        let package = format!("island_{}", self.spec.id.0.replace('-', "_"));
        island_manifest(&package, &runtime) + "\n[workspace]\n"
    }
}

fn collect_rust_files(
    root: &Path,
    dir: &Path,
    files: &mut BTreeMap<String, String>,
) -> Result<(), BuildError> {
    let entries = std::fs::read_dir(dir).map_err(|e| BuildError::io(dir, &e))?;
    for entry in entries {
        let path = entry.map_err(|e| BuildError::io(dir, &e))?.path();
        if path.is_dir() {
            collect_rust_files(root, &path, files)?;
        } else if path.extension().is_some_and(|ext| ext == "rs") {
            let source = std::fs::read_to_string(&path).map_err(|e| BuildError::io(&path, &e))?;
            let relative = path
                .strip_prefix(root)
                .expect("under root")
                .components()
                .map(|c| c.as_os_str().to_string_lossy())
                .collect::<Vec<_>>()
                .join("/");
            files.insert(relative, source);
        }
    }
    Ok(())
}

fn toml_string(text: &str) -> String {
    // TOML basic strings use JSON's escapes for everything a path can contain.
    serde_json::to_string(text).expect("strings serialise")
}

/// Settings for [`CargoIslandBuilder`].
#[derive(Debug, Clone)]
pub struct BuilderOptions {
    /// Holds the staging workspace (`build/`) and finished modules (`wasm/`). Keep it inside
    /// the project so the project's `rust-toolchain.toml`, if any, applies.
    pub cache_dir: PathBuf,
    /// Run `wasm-opt -O3` when it is on `PATH`.
    pub wasm_opt: bool,
    /// How to generate glue.
    pub glue: GlueOptions,
    /// The `PATH` to find tools on; `None` uses the process's.
    pub path: Option<std::ffi::OsString>,
}

impl BuilderOptions {
    /// Defaults: `wasm-opt` on, top-level-await glue, the process's `PATH`.
    pub fn new(cache_dir: PathBuf) -> Self {
        Self {
            cache_dir,
            wasm_opt: true,
            glue: GlueOptions::default(),
            path: None,
        }
    }
}

/// Builds islands with cargo, with a content-hash cache (see the [module docs](self)).
#[derive(Debug)]
pub struct CargoIslandBuilder {
    options: BuilderOptions,
    rustc: OnceLock<Result<Rustc, String>>,
    wasm_opt: OnceLock<Option<Tool>>,
    cargo_runs: AtomicUsize,
}

/// One island of a batch on its way through the builder.
struct Pending {
    index: usize,
    key: String,
}

impl CargoIslandBuilder {
    /// A builder with `options`. Nothing runs until the first build.
    pub fn new(options: BuilderOptions) -> Self {
        Self {
            options,
            rustc: OnceLock::new(),
            wasm_opt: OnceLock::new(),
            cargo_runs: AtomicUsize::new(0),
        }
    }

    /// How many times this builder has run cargo.
    pub fn cargo_invocations(&self) -> usize {
        self.cargo_runs.load(Ordering::Relaxed)
    }

    fn staging_dir(&self) -> PathBuf {
        self.options.cache_dir.join("build")
    }

    fn probe(&self) -> Probe {
        Probe {
            path: self.options.path.clone(),
            cwd: Some(self.staging_dir()),
        }
    }

    fn rustc(&self) -> Result<&Rustc, BuildError> {
        self.rustc
            .get_or_init(|| toolchain::rustc(&self.probe()))
            .as_ref()
            .map_err(|error| BuildError::ToolchainUnavailable(error.clone()))
    }

    fn wasm_opt(&self) -> Option<&Tool> {
        if !self.options.wasm_opt {
            return None;
        }
        self.wasm_opt
            .get_or_init(|| toolchain::wasm_opt(&self.probe()))
            .as_ref()
    }

    /// Writes the runtime crate into the staging workspace and returns its directory, for
    /// manifests that depend on it ([`IslandSource::manifest`]).
    pub fn materialize_runtime(&self) -> Result<PathBuf, BuildError> {
        let dir = self.staging_dir().join("trioxide_rt");
        write_if_changed(&dir.join("Cargo.toml"), &runtime_manifest())?;
        for (path, source) in RT_SOURCES {
            write_if_changed(&dir.join(path), source)?;
        }
        Ok(dir)
    }

    fn cache_key(&self, island: &IslandSource, rustc: &Rustc) -> String {
        let mut hasher = xxhash_rust::xxh3::Xxh3::new();
        let mut feed = |bytes: &[u8]| {
            hasher.update(&(bytes.len() as u64).to_le_bytes());
            hasher.update(bytes);
        };
        feed(b"trioxide island");
        feed(&ABI_VERSION.to_le_bytes());
        feed(RT_VERSION.as_bytes());
        feed(runtime_manifest().as_bytes());
        for (path, source) in RT_SOURCES {
            feed(path.as_bytes());
            feed(source.as_bytes());
        }
        feed(WORKSPACE_MANIFEST.as_bytes());
        feed(island_manifest("", "").as_bytes());
        feed(WASM_TARGET.as_bytes());
        feed(rustc.tool.version.as_bytes());
        feed(
            self.wasm_opt()
                .map_or(&b"no wasm-opt"[..], |tool| tool.version.as_bytes()),
        );
        for (path, source) in &island.files {
            feed(path.as_bytes());
            feed(source.as_bytes());
        }
        format!("{:032x}", hasher.digest128())
    }

    fn cached_path(&self, key: &str) -> PathBuf {
        self.options
            .cache_dir
            .join("wasm")
            .join(format!("{key}.wasm"))
    }

    fn artifact(
        &self,
        island: &IslandSource,
        wasm: Vec<u8>,
        warnings: Vec<String>,
    ) -> IslandArtifact {
        IslandArtifact {
            glue: generate_glue(&island.spec, &self.options.glue),
            spec: island.spec.clone(),
            wasm,
            warnings,
        }
    }

    /// Compiles the islands in `pending` (all cache misses) with one cargo run, then
    /// optimises and caches each module.
    fn compile(
        &self,
        islands: &[IslandSource],
        pending: &[Pending],
        results: &mut [Option<Result<IslandArtifact, BuildError>>],
    ) -> Result<(), BuildError> {
        let probe = self.probe();
        let cargo = toolchain::cargo(&probe).map_err(BuildError::ToolchainUnavailable)?;
        let rustc = self.rustc()?;
        if !rustc.has_wasm_target() {
            return Err(BuildError::ToolchainUnavailable(format!(
                "the {WASM_TARGET} target is not installed for rustc {}; run `rustup target add {WASM_TARGET}`",
                rustc.release
            )));
        }

        let staging = self.staging_dir();
        std::fs::create_dir_all(&staging).map_err(|e| BuildError::io(&staging, &e))?;
        let lock_path = staging.join(".lock");
        let lock = std::fs::File::create(&lock_path).map_err(|e| BuildError::io(&lock_path, &e))?;
        lock.lock().map_err(|e| BuildError::io(&lock_path, &e))?;

        write_if_changed(&staging.join("Cargo.toml"), WORKSPACE_MANIFEST)?;
        self.materialize_runtime()?;
        let packages: BTreeSet<String> = pending
            .iter()
            .map(|pending| package_name(&pending.key))
            .collect();
        let islands_dir = staging.join("islands");
        if let Ok(entries) = std::fs::read_dir(&islands_dir) {
            for entry in entries.flatten() {
                if !packages.contains(&*entry.file_name().to_string_lossy()) {
                    let _ = std::fs::remove_dir_all(entry.path());
                }
            }
        }
        for pending in pending {
            let dir = islands_dir.join(package_name(&pending.key));
            let island = &islands[pending.index];
            write_if_changed(
                &dir.join("Cargo.toml"),
                &island_manifest(&package_name(&pending.key), r#"path = "../../trioxide_rt""#),
            )?;
            for (path, source) in &island.files {
                write_if_changed(&dir.join(path), source)?;
            }
        }

        let mut command = probe.command(&cargo.path);
        command
            .args(["build", "--release", "--keep-going", "--color", "never"])
            .args(["--target", WASM_TARGET])
            .arg("--target-dir")
            .arg(staging.join("target"));
        for package in &packages {
            command.args(["-p", package]);
        }
        for (name, _) in std::env::vars_os() {
            if toolchain::is_scrubbed(&name) {
                command.env_remove(name);
            }
        }
        self.cargo_runs.fetch_add(1, Ordering::Relaxed);
        let output = command
            .output()
            .map_err(|e| BuildError::ToolchainUnavailable(format!("could not run cargo: {e}")))?;
        let stderr = String::from_utf8_lossy(&output.stderr).into_owned();

        let out_dir = staging.join("target").join(WASM_TARGET).join("release");
        for pending in pending {
            let island = &islands[pending.index];
            let built = out_dir.join(format!("{}.wasm", package_name(&pending.key)));
            // Package names come from cache keys, so an existing output was built from these
            // exact sources, possibly by an earlier run; it only counts as failed if cargo
            // says this package failed.
            let package = package_name(&pending.key);
            let failed = stderr.contains(&format!("`{package}`"));
            let result = match std::fs::read(&built) {
                Ok(wasm) if !failed => self.finish(island, &pending.key, &built, wasm),
                _ => Err(BuildError::Cargo {
                    island: island.spec.id.0.clone(),
                    stderr: stderr.clone(),
                }),
            };
            results[pending.index] = Some(result);
        }
        drop(lock);
        Ok(())
    }

    /// Runs `wasm-opt` if enabled and stores the module in the cache.
    fn finish(
        &self,
        island: &IslandSource,
        key: &str,
        built: &Path,
        wasm: Vec<u8>,
    ) -> Result<IslandArtifact, BuildError> {
        let mut warnings = Vec::new();
        let mut wasm = wasm;
        if let Some(tool) = self.wasm_opt() {
            let optimised = built.with_extension("opt.wasm");
            let status = self
                .probe()
                .command(&tool.path)
                .arg("-O3")
                .arg(built)
                .arg("-o")
                .arg(&optimised)
                .output();
            match status {
                Ok(output) if output.status.success() => {
                    wasm = std::fs::read(&optimised).map_err(|e| BuildError::io(&optimised, &e))?;
                }
                Ok(output) => warnings.push(format!(
                    "wasm-opt failed on island {}, using the unoptimised module: {}",
                    island.spec.id,
                    String::from_utf8_lossy(&output.stderr).trim()
                )),
                Err(error) => warnings.push(format!(
                    "could not run wasm-opt on island {}: {error}",
                    island.spec.id
                )),
            }
        }
        if warnings.is_empty() {
            write_atomically(&self.cached_path(key), &wasm)?;
        }
        Ok(self.artifact(island, wasm, warnings))
    }
}

fn package_name(key: &str) -> String {
    format!("island_{}", &key[..16])
}

fn write_if_changed(path: &Path, contents: &str) -> Result<(), BuildError> {
    if std::fs::read(path).is_ok_and(|existing| existing == contents.as_bytes()) {
        return Ok(());
    }
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent).map_err(|e| BuildError::io(parent, &e))?;
    }
    std::fs::write(path, contents).map_err(|e| BuildError::io(path, &e))
}

static TEMPORARY_FILES: AtomicUsize = AtomicUsize::new(0);

/// Writes via a temporary file and a rename, so readers never see a partial module.
fn write_atomically(path: &Path, bytes: &[u8]) -> Result<(), BuildError> {
    let dir = path.parent().expect("cache paths have a parent");
    std::fs::create_dir_all(dir).map_err(|e| BuildError::io(dir, &e))?;
    let temporary = dir.join(format!(
        ".{}.{}.tmp",
        std::process::id(),
        TEMPORARY_FILES.fetch_add(1, Ordering::Relaxed)
    ));
    let mut file = std::fs::File::create(&temporary).map_err(|e| BuildError::io(&temporary, &e))?;
    file.write_all(bytes)
        .and_then(|()| file.sync_all())
        .map_err(|e| BuildError::io(&temporary, &e))?;
    std::fs::rename(&temporary, path).map_err(|e| BuildError::io(path, &e))
}

impl IslandBuilder for CargoIslandBuilder {
    fn build(&self, island: &IslandSource) -> Result<IslandArtifact, BuildError> {
        self.build_all(std::slice::from_ref(island))
            .pop()
            .expect("one result per island")
    }

    fn build_all(&self, islands: &[IslandSource]) -> Vec<Result<IslandArtifact, BuildError>> {
        let mut results: Vec<Option<Result<IslandArtifact, BuildError>>> =
            vec![None; islands.len()];
        let mut pending = Vec::new();
        // rustc runs in the staging directory, so it must exist even for cache hits.
        let staging = std::fs::create_dir_all(self.staging_dir())
            .map_err(|error| BuildError::io(&self.staging_dir(), &error));
        for (index, island) in islands.iter().enumerate() {
            if let Err(error) = island.validate() {
                results[index] = Some(Err(BuildError::InvalidSpec(error)));
                continue;
            }
            if let Err(error) = &staging {
                results[index] = Some(Err(error.clone()));
                continue;
            }
            let rustc = match self.rustc() {
                Ok(rustc) => rustc,
                Err(error) => {
                    results[index] = Some(Err(error));
                    continue;
                }
            };
            let key = self.cache_key(island, rustc);
            if let Ok(wasm) = std::fs::read(self.cached_path(&key)) {
                results[index] = Some(Ok(self.artifact(island, wasm, Vec::new())));
            } else {
                // Islands with identical sources share a package and build once.
                pending.push(Pending { index, key });
            }
        }
        if !pending.is_empty()
            && let Err(error) = self.compile(islands, &pending, &mut results)
        {
            for pending in &pending {
                results[pending.index] = Some(Err(error.clone()));
            }
        }
        results
            .into_iter()
            .map(|result| result.expect("every island has a result"))
            .collect()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn embedded_runtime_is_complete() {
        let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("../trioxide_rt");
        let mut on_disk: Vec<String> = std::fs::read_dir(dir.join("src"))
            .unwrap()
            .map(|entry| format!("src/{}", entry.unwrap().file_name().to_string_lossy()))
            .collect();
        on_disk.sort();
        let embedded: Vec<&str> = RT_SOURCES.iter().map(|(path, _)| *path).collect();
        assert_eq!(on_disk, embedded, "update RT_SOURCES");

        let manifest = std::fs::read_to_string(dir.join("Cargo.toml")).unwrap();
        assert!(
            manifest.contains(&format!("libm = \"{RT_LIBM_REQUIREMENT}\"")),
            "RT_LIBM_REQUIREMENT must match crates/trioxide_rt/Cargo.toml"
        );
        assert_eq!(trioxide_rt::ABI_VERSION, ABI_VERSION);
        assert_eq!(trioxide_rt::VERSION, RT_VERSION);
    }
}
